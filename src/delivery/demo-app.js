function demoAppJs() {
  return `const cfg = window.ADP_DEMO || { items: [], name: 'Demo' };
const storageKey = (name) => 'adp-demo:' + cfg.name + ':' + name;
const items = cfg.items || [];
let selectedId = items[0]?.id || null;
let filter = '';
let favoritesOnly = false;
const favorites = new Set(JSON.parse(localStorage.getItem(storageKey('favorites')) || '[]'));
const plan = JSON.parse(localStorage.getItem(storageKey('plan')) || '{}');
const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

const grid = document.getElementById('grid');
const detail = document.getElementById('detail');
const search = document.getElementById('search');
const favBtn = document.getElementById('show-favorites');
const planBtn = document.getElementById('show-plan');
const favPanel = document.getElementById('favorites-panel');
const planPanel = document.getElementById('plan-panel');
const favList = document.getElementById('favorites-list');
const planDays = document.getElementById('plan-days');
const count = document.getElementById('catalog-count');

function visibleItems() {
  const q = filter.trim().toLowerCase();
  return items.filter((item) => {
    if (favoritesOnly && !favorites.has(item.id)) return false;
    if (!q) return true;
    return [item.title, item.blurb, ...(item.tags || [])].join(' ').toLowerCase().includes(q);
  });
}

function renderGrid() {
  const shown = visibleItems();
  count.textContent = shown.length + ' shown';
  grid.innerHTML = shown.map((item) => \`<article class="card\${item.id === selectedId ? ' selected' : ''}" data-id="\${item.id}"><div class="art" aria-hidden="true"></div><h3>\${esc(item.title)}</h3><p>\${esc(item.time)} · \${esc((item.tags || []).join(', '))}</p></article>\`).join('') || '<p class="meta">No matches.</p>';
}

function renderDetail(item) {
  if (!item) { detail.hidden = true; return; }
  detail.hidden = false;
  const saved = favorites.has(item.id);
  detail.innerHTML = \`<h2>\${esc(item.title)}</h2><p class="meta">\${esc(item.blurb)}</p><p><strong>Time:</strong> \${esc(item.time)}</p><h3>Ingredients</h3><ul>\${(item.ingredients || []).map((row) => \`<li>\${esc(row)}</li>\`).join('')}</ul><h3>Steps</h3><ol>\${(item.steps || []).map((row) => \`<li>\${esc(row)}</li>\`).join('')}</ol><button class="fav" id="toggle-fav" type="button">\${saved ? 'Remove from Favorites' : 'Save to Favorites'}</button>\`;
  document.getElementById('toggle-fav').onclick = () => {
    if (favorites.has(item.id)) favorites.delete(item.id); else favorites.add(item.id);
    localStorage.setItem(storageKey('favorites'), JSON.stringify([...favorites]));
    renderAll();
  };
}

function renderFavorites() {
  const rows = items.filter((item) => favorites.has(item.id));
  favList.innerHTML = rows.map((item) => \`<li>\${esc(item.title)}</li>\`).join('') || '<li>No favorites yet.</li>';
}

function renderPlan() {
  planDays.innerHTML = days.map((day) => {
    const id = plan[day];
    const item = items.find((row) => row.id === id);
    return \`<button class="day" data-day="\${day}" type="button"><strong>\${day}</strong><span>\${item ? esc(item.title) : 'Add item'}</span></button>\`;
  }).join('');
}

function renderAll() {
  renderGrid();
  renderDetail(items.find((item) => item.id === selectedId));
  renderFavorites();
  renderPlan();
}

grid.addEventListener('click', (event) => {
  const card = event.target.closest('[data-id]');
  if (!card) return;
  selectedId = card.dataset.id;
  favPanel.hidden = true;
  planPanel.hidden = true;
  renderAll();
});

search.addEventListener('input', () => {
  filter = search.value;
  favoritesOnly = false;
  renderAll();
});

favBtn.addEventListener('click', () => {
  favoritesOnly = !favoritesOnly;
  favPanel.hidden = !favoritesOnly;
  planPanel.hidden = true;
  favBtn.textContent = favoritesOnly ? 'All items' : 'Favorites';
  renderAll();
});

planBtn.addEventListener('click', () => {
  planPanel.hidden = !planPanel.hidden;
  favPanel.hidden = true;
  renderAll();
});

planDays.addEventListener('click', (event) => {
  const day = event.target.closest('[data-day]')?.dataset.day;
  if (!day || !selectedId) return;
  if (plan[day] === selectedId) delete plan[day];
  else plan[day] = selectedId;
  localStorage.setItem(storageKey('plan'), JSON.stringify(plan));
  renderAll();
});

function esc(value) {
  return String(value || '').replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
}

renderAll();
`;
}

function demoReadme(config) {
  return `# ${config.name}

${config.summary}

${DEMO_APP_DISCLAIMER}

## Try this
${(config.journeys || []).map(item => `- ${item}`).join('\n')}

Open \`index.html\` in a browser, or use **Open App** from the owner dashboard.
`;
}

function escapeHtml(value) {
  return String(value || '').replace(/[&<>"']/g, char => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  }[char]));
}
