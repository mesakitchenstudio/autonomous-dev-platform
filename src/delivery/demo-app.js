import { specProductName } from '../orchestrator/gate.js';

export const DEMO_APP_DISCLAIMER = 'This application was generated by the ADP demo using MOCK Council/Cursor execution. It is intended to demonstrate the owner workflow and is not a production-verified build.';

const RECIPE_JOURNEYS = [
  'Browse the available recipes.',
  'Search for a recipe.',
  'Open recipe details.',
  'Save a recipe to Favorites.',
  'Add a recipe to the weekly meal plan.'
];

const GENERIC_JOURNEYS = [
  'Browse the available items.',
  'Search or filter the catalog.',
  'Open an item to view details.',
  'Save an item to Favorites.',
  'Add an item to this week\'s plan.'
];

export function isDemoDelivery(project) {
  return Boolean(project?.demo);
}

export function isRecipeFixture(project) {
  const text = `${project?.idea || ''} ${specProductName(project?.council?.discovery?.spec) || ''}`.toLowerCase();
  return /\brecipe|\bmeal plan/.test(text);
}

export function lastOwnerFeedback(project) {
  return (project?.ownerReviews || []).filter(item => item.decision === 'CHANGES_REQUESTED').at(-1)?.feedback
    || project?.pendingOwnerFeedback?.feedback
    || '';
}

export function demoProductName(project) {
  const specName = specProductName(project?.council?.discovery?.spec);
  if (specName && specName !== 'Generated Application') return specName;
  if (isRecipeFixture(project)) return 'Recipe Box';
  return specName || 'Generated Application';
}

export function demoProductSummary(project) {
  const spec = project?.council?.discovery?.spec || {};
  return spec.productSummary
    || spec.product?.summary
    || (isRecipeFixture(project)
      ? 'Browse recipes, search, open details, save favorites, and plan the week.'
      : (project?.idea || 'A demo application for owner review.'));
}

export function demoOwnerJourneys(project) {
  if (isRecipeFixture(project)) return [...RECIPE_JOURNEYS];
  const fromSpec = flattenGuidance(project?.council?.discovery?.spec?.requirements)
    .filter(item => !/test|runtime verification|secrets in source|maintainable structure/i.test(item));
  if (fromSpec.length >= 3) return fromSpec.slice(0, 6);
  return [...GENERIC_JOURNEYS];
}

export function flattenGuidance(value) {
  if (Array.isArray(value)) return value.flatMap(item => flattenGuidance(item));
  if (value && typeof value === 'object') {
    if (value.title) return [String(value.title)];
    return Object.values(value).flatMap(item => flattenGuidance(item));
  }
  if (value == null || value === '') return [];
  return [String(value)];
}

export function demoRevisionOptions(project, version = 1) {
  const feedback = lastOwnerFeedback(project);
  return {
    version,
    feedback,
    compactHome: version > 1 && /busy|clutter|simple|fewer|spacious/i.test(feedback),
    largerImages: version > 1 && /larger|bigger|image/i.test(feedback)
  };
}

export function buildDemoAppFiles(project, { version } = {}) {
  const recipe = isRecipeFixture(project);
  const name = demoProductName(project);
  const summary = demoProductSummary(project);
  const deliveryVersion = Number(version || Math.max(1, ...(project?.deliveries || []).map(item => Number(item.version || 0)), 1));
  const revision = demoRevisionOptions(project, deliveryVersion);
  const config = {
    fixture: recipe ? 'recipe' : 'generic',
    name,
    summary,
    version: revision.version,
    feedback: revision.feedback || '',
    compactHome: revision.compactHome,
    largerImages: revision.largerImages,
    journeys: demoOwnerJourneys(project),
    items: recipe ? recipeCatalog() : genericCatalog(project, name)
  };
  return {
    'index.html': demoIndexHtml(config),
    'styles.css': demoStylesCss(config),
    'app.js': demoAppJs(),
    'README.md': demoReadme(config)
  };
}

export async function writeDemoAppFiles(dir, project, options = {}) {
  const files = buildDemoAppFiles(project, options);
  await fs.mkdir(dir, { recursive: true });
  const names = [];
  for (const [rel, contents] of Object.entries(files)) {
    await fs.writeFile(path.join(dir, rel), contents, 'utf8');
    names.push(rel);
  }
  return names;
}

